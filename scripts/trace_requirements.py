#!/usr/bin/env python3
"""Requirement traceability matrix: PRD requirement IDs -> automated tests.

Sources
  * Requirements: docs/01-prd.md table rows ``| AREA-NNN | text | Pri | Phase | ... |``.
  * Backend tests: ``@pytest.mark.req("AREA-NNN", ...)`` / ``pytestmark = pytest.mark.req(...)``.
  * TypeScript tests (mobile/, apps/, packages/): comments ``req: AREA-NNN[, AREA-NNN]``.

Usage
  python scripts/trace_requirements.py [--output reports/traceability.md] [--enforce-phases 0,1]

Exit code 1 when a test references an unknown requirement ID, or when a *Must* requirement of an
enforced phase has no test. Standard library only so it runs anywhere.
"""

from __future__ import annotations

import argparse
import re
import sys
from collections import defaultdict
from dataclasses import dataclass, field
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
PRD_PATH = REPO_ROOT / "docs" / "01-prd.md"
CONTRACT_PATH = REPO_ROOT / "contracts" / "openapi" / "openapi.yaml"

# Prefixes may contain digits (e.g. I18N-001).
_ID = r"[A-Z][A-Z0-9]{1,5}-\d{3}"
ID_PATTERN = re.compile(rf"\b({_ID})\b")
PRD_ROW = re.compile(rf"^\|\s*(?P<id>{_ID})\s*\|(?P<rest>.*)$")
PY_MARKER = re.compile(r"mark\.req\(([^)]*)\)", re.DOTALL)
TS_MARKER = re.compile(rf"req:\s*((?:{_ID})(?:\s*,\s*{_ID})*)")
CONTRACT_REQS = re.compile(r"^\s*x-requirements:\s*\[(.*)\]\s*$", re.MULTILINE)
TS_SUFFIXES = (".test.ts", ".test.tsx", ".spec.ts", ".spec.tsx")
SKIP_DIRS = {"node_modules", ".venv", ".git", "__pycache__", ".expo", ".next", "dist", "build"}


@dataclass
class Requirement:
    req_id: str
    text: str
    priority: str
    phase: int | None
    tests: list[str] = field(default_factory=list)
    contract_ops: int = 0


def _first_int(text: str) -> int | None:
    match = re.search(r"\d+", text)
    return int(match.group()) if match else None


def parse_prd(path: Path) -> dict[str, Requirement]:
    requirements: dict[str, Requirement] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        match = PRD_ROW.match(line.strip())
        if not match or "~~" in line:  # superseded requirements are struck through
            continue
        cells = [c.strip() for c in match.group("rest").split("|")]
        req_id = match.group("id")
        text = cells[0] if cells else ""
        # Functional tables: | ID | Requirement | Pri | Phase | Acceptance |
        # NFR table:         | ID | Requirement | Target |
        priority = cells[1] if len(cells) > 3 and cells[1] in {"M", "S", "C"} else ""
        phase = _first_int(cells[2]) if priority else None
        requirements.setdefault(req_id, Requirement(req_id, text, priority, phase))
    return requirements


def _walk(root: Path) -> list[Path]:
    if not root.exists():
        return []
    files: list[Path] = []
    for path in root.rglob("*"):
        if any(part in SKIP_DIRS for part in path.parts):
            continue
        if path.is_file():
            files.append(path)
    return files


def collect_contract_references() -> dict[str, int]:
    """Count OpenAPI operations per requirement ID (``x-requirements`` flow lists)."""
    counts: dict[str, int] = defaultdict(int)
    if CONTRACT_PATH.exists():
        for match in CONTRACT_REQS.finditer(CONTRACT_PATH.read_text(encoding="utf-8")):
            for req_id in set(ID_PATTERN.findall(match.group(1))):
                counts[req_id] += 1
    return counts


def collect_test_references() -> dict[str, list[str]]:
    references: dict[str, list[str]] = defaultdict(list)

    for path in _walk(REPO_ROOT / "backend" / "tests"):
        if path.suffix != ".py":
            continue
        text = path.read_text(encoding="utf-8")
        for match in PY_MARKER.finditer(text):
            line = text.count("\n", 0, match.start()) + 1
            for req_id in ID_PATTERN.findall(match.group(1)):
                references[req_id].append(f"{path.relative_to(REPO_ROOT).as_posix()}:{line}")

    for root_name in ("mobile", "apps", "packages"):
        for path in _walk(REPO_ROOT / root_name):
            if not path.name.endswith(TS_SUFFIXES):
                continue
            text = path.read_text(encoding="utf-8")
            for match in TS_MARKER.finditer(text):
                line = text.count("\n", 0, match.start()) + 1
                for req_id in ID_PATTERN.findall(match.group(1)):
                    references[req_id].append(f"{path.relative_to(REPO_ROOT).as_posix()}:{line}")
    return references


def render(requirements: dict[str, Requirement], unknown: dict[str, list[str]]) -> str:
    by_area: dict[str, list[Requirement]] = defaultdict(list)
    for req in requirements.values():
        by_area[req.req_id.split("-")[0]].append(req)

    lines = [
        "# Requirement traceability matrix",
        "",
        "Generated by `scripts/trace_requirements.py`. Do not edit by hand.",
        "",
        "| Area | Requirements | Must | Traced | Must traced |",
        "|---|---|---|---|---|",
    ]
    for area in sorted(by_area):
        reqs = by_area[area]
        must = [r for r in reqs if r.priority == "M"]
        lines.append(
            f"| {area} | {len(reqs)} | {len(must)} | {sum(bool(r.tests) for r in reqs)} "
            f"| {sum(bool(r.tests) for r in must)} |"
        )
    lines += ["", "| ID | Pri | Phase | Contract ops | Tests |", "|---|---|---|---|---|"]
    for req in sorted(requirements.values(), key=lambda r: r.req_id):
        tests = "<br>".join(f"`{t}`" for t in req.tests) or "—"
        phase = "" if req.phase is None else str(req.phase)
        lines.append(f"| {req.req_id} | {req.priority} | {phase} | {req.contract_ops} | {tests} |")
    if unknown:
        lines += ["", "## Unknown requirement IDs referenced by tests", ""]
        for req_id, refs in sorted(unknown.items()):
            lines.append(f"- `{req_id}`: {', '.join(refs)}")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--output", type=Path, help="write the Markdown matrix to this path")
    parser.add_argument(
        "--enforce-phases",
        default="",
        help="comma-separated phases whose Must requirements must all be traced (e.g. 0,1)",
    )
    args = parser.parse_args(argv)

    requirements = parse_prd(PRD_PATH)
    references = collect_test_references()
    contract = collect_contract_references()
    unknown = {k: v for k, v in references.items() if k not in requirements}
    unknown.update(
        {k: ["contracts/openapi/openapi.yaml"] for k in contract if k not in requirements}
    )
    for req_id, count in contract.items():
        if req_id in requirements:
            requirements[req_id].contract_ops = count
    for req_id, refs in references.items():
        if req_id in requirements:
            requirements[req_id].tests = sorted(set(refs))

    report = render(requirements, unknown)
    if args.output:
        output = args.output if args.output.is_absolute() else REPO_ROOT / args.output
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(report, encoding="utf-8")

    enforced = {int(p) for p in args.enforce_phases.split(",") if p.strip()}
    untraced = sorted(
        r.req_id
        for r in requirements.values()
        if r.priority == "M" and r.phase in enforced and not r.tests
    )
    traced = sum(bool(r.tests) for r in requirements.values())
    print(f"requirements: {len(requirements)}  traced: {traced}  unknown refs: {len(unknown)}")
    failed = False
    if unknown:
        print(
            f"ERROR unknown requirement IDs in tests/contract: {sorted(unknown)}", file=sys.stderr
        )
        failed = True
    if untraced:
        print(
            f"ERROR untraced Must requirements in phases {sorted(enforced)}: {untraced}",
            file=sys.stderr,
        )
        failed = True
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
